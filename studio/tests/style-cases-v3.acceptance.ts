import assert from 'node:assert/strict';
import { once } from 'node:events';
import type { AddressInfo } from 'node:net';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';
import { createStudio } from '../src/server.ts';
import { ROOT } from '../src/projects.ts';
import { editorialCases } from '../research/style-cases/v3.ts';

const data = await editorialCases(), server = createStudio();
server.listen(0, '127.0.0.1'); await once(server, 'listening');
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 960 } });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  await page.goto(`${base}/films/style-case-candidates-v3/index.html`);
  await page.evaluate(() => localStorage.setItem('lemo-style-case-candidates-v2', JSON.stringify({ 'ink-wash': { choice: 'C', note: 'Old draft must not migrate' } })));
  await page.reload();
  assert.equal(await page.locator('article').count(), 99);
  assert.equal(await page.locator('input[type=radio]').count(), 297);
  assert.equal(await page.locator('input[type=radio]:checked').count(), 0);
  await page.locator('#pending').check();
  assert.equal(await page.locator('article:visible').count(), 99 - data.counts.editorialAudiovisual);
  await page.locator('#pending').uncheck();
  await page.locator('#search').fill('这句已经改过的话');
  assert.equal(await page.locator('article:visible').count(), 1);
  await page.locator('#dark-keynote input[value=A]').check();
  await page.locator('#dark-keynote textarea').fill('先验证真实版本链，再决定。');
  await page.reload();
  assert.equal(await page.locator('#dark-keynote input[value=A]').isChecked(), true);
  assert.equal(await page.locator('#dark-keynote textarea').inputValue(), '先验证真实版本链，再决定。');
  await page.locator('#unselected').check();
  assert.equal(await page.locator('article:visible').count(), 98);
  await page.locator('#jump').selectOption('silent-film');
  assert.equal(await page.locator('#unselected').isChecked(), false);
  await page.locator('#silent-film .timeline summary').click();
  assert.ok(await page.locator('#silent-film .timeline li').count() >= 8);
  // Intercept the official URL to test player controls without treating network playback as observation.
  await page.route('https://github.com/lemomo-ai/lemo-opuscar/releases/download/web/silent-film.mp4', route => route.fulfill({ path: path.join(ROOT, '.studio/style-reference-review/silent-film.mp4'), contentType: 'video/mp4' }));
  await page.locator('#silent-film header button').click();
  assert.equal(await page.locator('#player').isVisible(), true);
  await page.locator('video').evaluate((v: HTMLVideoElement) => { v.preload = 'metadata'; v.load(); });
  await page.waitForFunction(() => document.querySelector('video')!.readyState >= 1);
  assert.ok(await page.locator('video').evaluate((v: HTMLVideoElement) => v.duration) > 50);
  await page.locator('#close-player').click();
  assert.equal(await page.locator('video').evaluate((v: HTMLVideoElement) => v.paused), true);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const exported = JSON.parse(await fs.readFile((await (await downloadPromise).path())!, 'utf8'));
  assert.equal(exported.status, 'discussion-draft-not-production-approval');
  assert.equal(exported.rows.length, 99);
  assert.equal(exported.rows.find((r: { slug: string }) => r.slug === 'dark-keynote').choice, 'A');
  await page.locator('#dark-keynote [data-clear]').click();
  assert.equal(await page.locator('input[type=radio]:checked').count(), 0);
  const out = path.join(ROOT, '.studio/style-cases-v3'); await fs.mkdir(out, { recursive: true });
  await page.evaluate(() => scrollTo(0, 0)); await page.screenshot({ path: path.join(out, 'desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(out, 'mobile.png') });
  assert.equal((await page.request.get(`${base}/films/style-case-candidates-v3/content.json`)).status(), 200);
  assert.deepEqual(errors, []);
  console.log('v3 acceptance passed: isolated choices, filters, full timelines, original player, export and mobile layout.');
} finally { await browser.close(); server.close(); }
