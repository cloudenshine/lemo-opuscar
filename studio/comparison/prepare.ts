import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { ROOT, createProject, within, content } from '../src/projects.ts';
import { renderProject, run } from '../src/render.ts';

const manifest = JSON.parse(await fs.readFile(path.join(ROOT, 'studio/comparison/sources.json'), 'utf8'));
const media = path.join(ROOT, '.studio/comparison/source');
await fs.mkdir(media, { recursive: true });
for (const pair of manifest.pairs) {
  const target = path.join(media, `${pair.id}.mp4`);
  let bytes: Buffer;
  try { bytes = await fs.readFile(await within(media, `${pair.id}.mp4`)); }
  catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    const response = await fetch(pair.original, { signal: AbortSignal.timeout(120000) });
    if (!response.ok) throw new Error(`Download failed: ${response.status} ${pair.id}`);
    bytes = Buffer.from(await response.arrayBuffer());
    if (createHash('sha256').update(bytes).digest('hex') !== pair.sha256) throw new Error(`Original changed: ${pair.id}. Review the upstream release before updating its hash.`);
    await fs.writeFile(target, bytes, { flag: 'wx' });
  }
  if (createHash('sha256').update(bytes).digest('hex') !== pair.sha256) throw new Error(`Source checksum mismatch: ${pair.id}`);
  const films = path.join(ROOT, 'films');
  const exists = await fs.stat(path.join(films, pair.project)).then(() => true).catch((e: NodeJS.ErrnoException) => { if (e.code !== 'ENOENT') throw e; return false; });
  if (!exists) {
    const style = JSON.parse(await fs.readFile(path.join(ROOT, 'personal-styles', pair.personal, 'style.json'), 'utf8'));
    await createProject(pair.project, content(style.defaults), films, pair.personal);
    await renderProject(pair.project, console.log);
  } else {
    // Existing work is never regenerated by this preparation command.
    const metadata = JSON.parse(await fs.readFile(await within(films, `${pair.project}/project.json`), 'utf8'));
    if (metadata.style !== pair.personal) throw new Error(`Reserved sample name belongs to another style: ${pair.project}`);
    await within(films, `${pair.project}/out/film.mp4`);
  }
  console.log(`Ready: ${pair.name}`);
}
await run(process.execPath, ['studio/comparison/analyze.ts'], s => process.stdout.write(s));
